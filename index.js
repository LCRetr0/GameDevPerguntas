let niveis = [Facil, Intermediario, Dificil];
let nivelAtualIndex = localStorage.getItem("quiz_nivel") ? parseInt(localStorage.getItem("quiz_nivel")) : 0;
let perguntaAtualIndex = localStorage.getItem("quiz_pergunta") ? parseInt(localStorage.getItem("quiz_pergunta")) : 0;
let scoreTotal = localStorage.getItem("quiz_score") ? parseInt(localStorage.getItem("quiz_score")) : 0;

const spanNivel = document.getElementById("nivel");
const spanScore = document.getElementById("score");
const h2Pergunta = document.getElementById("pergunta");
const divRespostas = document.getElementById("respostas");
const btnProximo = document.getElementById("proximo");

const nomesNiveis = ["Fácil", "Intermediário", "Difícil"];

function iniciarQuiz() {
 
    carregarPergunta();
}

function carregarPergunta() {
    limparTela();
    
    let nivelAtual = niveis[nivelAtualIndex];
    let atual = nivelAtual[perguntaAtualIndex];

    spanNivel.innerText = nomesNiveis[nivelAtualIndex];
    spanScore.innerText = scoreTotal;
    h2Pergunta.innerText = atual.pergunta;

    atual.respostas.forEach((textoResposta, index) => {
        const button = document.createElement("button");
        button.innerText = textoResposta;
        button.classList.add("btn");

        if (index === atual.correta) {
            button.dataset.correto = "true";
        } else {
            button.dataset.correto = "false";
        }

        button.addEventListener("click", selecionarResposta);
        divRespostas.appendChild(button);
    });
}

function limparTela() {
    btnProximo.style.display = "none";
    while (divRespostas.firstChild) {
        divRespostas.removeChild(divRespostas.firstChild);
    }
}

function selecionarResposta(e) {
    const botaoSelecionado = e.target;
    const ehCorreto = botaoSelecionado.dataset.correto === "true";

    if (ehCorreto) {
        scoreTotal++;
        spanScore.innerText = scoreTotal;
    }

    Array.from(divRespostas.children).forEach(button => {
        if (button.dataset.correto === "true") {
            button.classList.add("correto");
        } else {
            button.classList.add("errado");
        }
        button.disabled = true;
    });

    salvarProgresso();

    btnProximo.style.display = "block";
}

btnProximo.addEventListener("click", () => {
    perguntaAtualIndex++;
    let nivelAtual = niveis[nivelAtualIndex];

    if (perguntaAtualIndex < nivelAtual.length) {
        carregarPergunta();
    } else {
        nivelAtualIndex++;
        perguntaAtualIndex = 0; 

        if (nivelAtualIndex < niveis.length) {
            carregarPergunta();
        } else {
            h2Pergunta.innerText = `Parabéns! Você concluiu o quiz com ${scoreTotal} pontos!`;
            divRespostas.innerHTML = "";
            btnProximo.style.display = "none";
            spanNivel.innerText = "Fim";
            
           
            localStorage.clear();
            return;
        }
    }
    

    salvarProgresso();
});


function salvarProgresso() {
    localStorage.setItem("quiz_nivel", nivelAtualIndex);
    localStorage.setItem("quiz_pergunta", perguntaAtualIndex);
    localStorage.setItem("quiz_score", scoreTotal);
}



// Inicializa o jogo
iniciarQuiz();